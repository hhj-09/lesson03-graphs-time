import streamlit as st
import pandas as pd
import plotly.express as px


# ==================================================
# 페이지 설정
# ==================================================

st.set_page_config(
    page_title="영화 데이터 그래프 도감 1 - 시간",
    page_icon="🎬",
    layout="wide"
)

st.title("🎬 영화 데이터 그래프 도감 1 - 시간")

st.write(
    "1년치 일별 박스오피스 데이터를 이용해 "
    "영화의 관객 변화를 그래프로 살펴봅니다."
)


# ==================================================
# 데이터 불러오기
# ==================================================

DATA_URL = (
    "https://raw.githubusercontent.com/greatsong/"
    "modudata/main/data/kobis_daily.csv"
)

try:
    # CSV 파일을 인터넷에서 불러옵니다.
    df = pd.read_csv(DATA_URL)

except Exception as e:
    st.error("데이터를 불러오지 못했습니다.")
    st.write(f"오류 내용: {e}")
    st.stop()


# ==================================================
# 데이터 전처리
# ==================================================

# 날짜가 20250901처럼 8자리 숫자로 되어 있으므로
# 실제 날짜 자료형으로 변환합니다.
df["날짜"] = pd.to_datetime(
    df["날짜"].astype(str),
    format="%Y%m%d"
)

# 숫자로 사용할 열은 숫자형으로 변환합니다.
numeric_columns = [
    "순위",
    "영화코드",
    "일관객",
    "누적관객",
    "스크린수",
    "상영횟수"
]

for column in numeric_columns:
    df[column] = pd.to_numeric(
        df[column],
        errors="coerce"
    )


# 날짜순으로 정렬합니다.
df = df.sort_values("날짜")


# ==================================================
# 전체 데이터 정보
# ==================================================

st.info(
    f"📅 데이터 기간: "
    f"{df['날짜'].min().strftime('%Y년 %m월 %d일')} ~ "
    f"{df['날짜'].max().strftime('%Y년 %m월 %d일')}  "
    f" | 총 {len(df):,}개의 기록"
)


# ==================================================
# 그래프 구역 1
# ==================================================

st.divider()

st.header("1. 시간에 따른 일관객 변화")

st.write(
    "영화를 하나 선택하면 해당 영화가 "
    "날짜별로 얼마나 많은 관객을 모았는지 볼 수 있습니다."
)


# --------------------------------------------------
# 영화 선택
# --------------------------------------------------

# 영화 목록을 중복 없이 가져옵니다.
movie_list = sorted(
    df["영화명"].dropna().unique()
)

selected_movie = st.selectbox(
    "영화를 선택하세요.",
    movie_list
)


# --------------------------------------------------
# 선택한 영화의 데이터만 가져오기
# --------------------------------------------------

movie_df = df[
    df["영화명"] == selected_movie
].copy()

# 날짜순으로 정렬합니다.
movie_df = movie_df.sort_values("날짜")


# --------------------------------------------------
# Plotly 선 그래프
# --------------------------------------------------

fig = px.line(
    movie_df,
    x="날짜",
    y="일관객",
    markers=True,
    title=f"{selected_movie}의 날짜별 일관객 변화",
    labels={
        "날짜": "날짜",
        "일관객": "일관객 수"
    }
)


# 마우스를 그래프 위에 올렸을 때
# 날짜와 관객수가 나타나도록 설정합니다.
fig.update_traces(
    hovertemplate=(
        "날짜: %{x|%Y-%m-%d}<br>"
        "일관객: %{y:,}명"
        "<extra></extra>"
    )
)

# 그래프의 크기와 모양을 설정합니다.
fig.update_layout(
    hovermode="x",
    height=500
)


# 그래프 출력
st.plotly_chart(
    fig,
    use_container_width=True
)


# --------------------------------------------------
# 그래프로 알 수 있는 것
# --------------------------------------------------

st.markdown("**이 그래프로 알 수 있는 것**")

st.text_area(
    "이 그래프에서 발견한 점을 적어 보세요.",
    placeholder=(
        "예: 주말에 관객수가 증가하고 평일에는 감소하는 "
        "경향을 확인할 수 있다."
    ),
    height=100,
    key="graph1_note"
)


# ==================================================
# 앞으로 그래프를 추가할 공간
# ==================================================

st.divider()

st.header("2. 다음 그래프")

st.info(
    "앞으로 새로운 그래프를 추가할 공간입니다."
)

st.markdown(
    "**이 그래프로 알 수 있는 것**"
)

st.text_area(
    "다음 그래프에서 발견한 점을 적어 보세요.",
    placeholder="그래프를 추가한 뒤 발견한 내용을 적어 보세요.",
    height=100,
    key="graph2_note"
)


# ==================================================
# 그래프 구역 3
# ==================================================

st.divider()

st.header("3. 다음 그래프")

st.info(
    "새로운 데이터 분석 그래프를 추가할 공간입니다."
)

st.markdown(
    "**이 그래프로 알 수 있는 것**"
)

