import streamlit as st
import pandas as pd
import plotly.express as px


# ==================================================
# 페이지 설정
# ==================================================

st.set_page_config(
    page_title="영화 데이터 그래프 도감 1 - 시간",
    page_icon="🎬",
    layout="wide"
)

st.title("🎬 영화 데이터 그래프 도감 1 - 시간")

st.write(
    "1년치 일별 박스오피스 데이터를 이용해 "
    "영화의 관객 변화를 시간에 따라 살펴봅니다."
)


# ==================================================
# 데이터 불러오기
# ==================================================

DATA_URL = (
    "https://raw.githubusercontent.com/greatsong/"
    "modudata/main/data/kobis_daily.csv"
)

try:
    df = pd.read_csv(DATA_URL)

except Exception as e:
    st.error("데이터를 불러오지 못했습니다.")
    st.write(f"오류 내용: {e}")
    st.stop()


# ==================================================
# 데이터 전처리
# ==================================================

# 20250901처럼 되어 있는 날짜를
# 실제 날짜 자료형으로 변환합니다.
df["날짜"] = pd.to_datetime(
    df["날짜"].astype(str),
    format="%Y%m%d"
)

# 숫자로 사용할 열은 숫자형으로 변환합니다.
numeric_columns = [
    "순위",
    "영화코드",
    "일관객",
    "누적관객",
    "스크린수",
    "상영횟수"
]

for column in numeric_columns:
    df[column] = pd.to_numeric(
        df[column],
        errors="coerce"
    )

# 날짜순으로 정렬합니다.
df = df.sort_values("날짜")


# ==================================================
# 전체 데이터 정보
# ==================================================

st.info(
    f"📅 데이터 기간: "
    f"{df['날짜'].min().strftime('%Y년 %m월 %d일')} ~ "
    f"{df['날짜'].max().strftime('%Y년 %m월 %d일')} "
    f"| 총 {len(df):,}개의 기록"
)


# ==================================================
# 그래프 구역 1
# ==================================================

st.divider()

st.header("1. 시간에 따른 일관객 변화")

st.write(
    "영화를 하나 선택하면 해당 영화의 "
    "날짜별 일관객 변화를 볼 수 있습니다."
)


# --------------------------------------------------
# 영화 선택
# --------------------------------------------------

movie_list = sorted(
    df["영화명"].dropna().unique()
)

selected_movie = st.selectbox(
    "영화를 선택하세요.",
    movie_list
)


# --------------------------------------------------
# 선택한 영화의 데이터
# --------------------------------------------------

movie_df = df[
    df["영화명"] == selected_movie
].copy()

movie_df = movie_df.sort_values("날짜")


# --------------------------------------------------
# 첫 번째 그래프
# --------------------------------------------------

fig = px.line(
    movie_df,
    x="날짜",
    y="일관객",
    markers=True,
    title=f"{selected_movie}의 날짜별 일관객 변화",
    labels={
        "날짜": "날짜",
        "일관객": "일관객 수"
    }
)

fig.update_traces(
    hovertemplate=(
        "날짜: %{x|%Y-%m-%d}<br>"
        "일관객: %{y:,}명"
        "<extra></extra>"
    )
)

fig.update_layout(
    hovermode="x",
    height=500
)

st.plotly_chart(
    fig,
    use_container_width=True
)


# --------------------------------------------------
# 첫 번째 그래프 해석 공간
# --------------------------------------------------

st.markdown("**이 그래프로 알 수 있는 것**")

st.text_area(
    "첫 번째 그래프에서 발견한 점을 적어 보세요.",
    placeholder=(
        "예: 개봉 직후 관객수가 높고 이후 점차 감소하는 "
        "경향을 확인할 수 있다."
    ),
    height=100,
    key="graph1_note"
)


# ==================================================
# 그래프 구역 2
# ==================================================

st.divider()

st.header("2. 일관객 합계가 가장 큰 영화 5편의 변화")

st.write(
    "전체 기간 동안의 일관객 합계를 기준으로 "
    "관객수가 가장 많았던 5편의 날짜별 변화를 비교합니다."
)


# --------------------------------------------------
# 영화별 전체 기간 일관객 합계
# --------------------------------------------------

movie_total = (
    df.groupby("영화명", as_index=False)["일관객"]
    .sum()
    .sort_values(
        "일관객",
        ascending=False
    )
)

top5_movies = movie_total.head(5)["영화명"].tolist()


# --------------------------------------------------
# 상위 5편의 데이터만 추출
# --------------------------------------------------

top5_df = df[
    df["영화명"].isin(top5_movies)
].copy()

top5_df = top5_df.sort_values(
    ["날짜", "영화명"]
)


# --------------------------------------------------
# 두 번째 그래프
# --------------------------------------------------

fig2 = px.line(
    top5_df,
    x="날짜",
    y="일관객",
    color="영화명",
    markers=True,
    title="일관객 합계 상위 5편의 날짜별 일관객",
    labels={
        "날짜": "날짜",
        "일관객": "일관객 수",
        "영화명": "영화"
    }
)

fig2.update_traces(
    hovertemplate=(
        "영화: %{fullData.name}<br>"
        "날짜: %{x|%Y-%m-%d}<br>"
        "일관객: %{y:,}명"
        "<extra></extra>"
    )
)

fig2.update_layout(
    hovermode="x unified",
    height=600,
    legend_title_text="영화"
)

st.plotly_chart(
    fig2,
    use_container_width=True
)


# --------------------------------------------------
# 두 번째 그래프 해석 공간
# --------------------------------------------------

st.markdown("**이 그래프로 알 수 있는 것**")

st.text_area(
    "두 번째 그래프에서 발견한 점을 적어 보세요.",
    placeholder=(
        "예: 영화마다 개봉 이후 관객수가 증가하고 감소하는 "
        "시점과 정도가 서로 다르다는 것을 알 수 있다."
    ),
    height=100,
    key="graph2_note"
)


# ==================================================
# 그래프 구역 3
# ==================================================

st.divider()

st.header("3. 날짜별 10위권 전체 일관객")

st.write(
    "각 날짜의 박스오피스 10위권 영화들의 일관객을 "
    "모두 합산하여 전체적인 영화 관람 규모의 변화를 살펴봅니다."
)


# --------------------------------------------------
# 날짜별 10위권 일관객 합계 계산
# --------------------------------------------------

daily_total = (
    df.groupby("날짜", as_index=False)["일관객"]
    .sum()
)

daily_total = daily_total.sort_values("날짜")


# --------------------------------------------------
# 일관객 합계가 가장 큰 3일 찾기
# --------------------------------------------------

top3_days = (
    daily_total
    .nlargest(3, "일관객")
    .sort_values("날짜")
)


# --------------------------------------------------
# 세 번째 그래프
# --------------------------------------------------

fig3 = px.area(
    daily_total,
    x="날짜",
    y="일관객",
    title="날짜별 박스오피스 10위권 일관객 합계",
    labels={
        "날짜": "날짜",
        "일관객": "10위권 일관객 합계"
    }
)


# 마우스를 올렸을 때 날짜와 합계를 표시합니다.
fig3.update_traces(
    hovertemplate=(
        "날짜: %{x|%Y-%m-%d}<br>"
        "10위권 일관객 합계: %{y:,}명"
        "<extra></extra>"
    )
)


# --------------------------------------------------
# 상위 3일을 그래프 위에 표시
# --------------------------------------------------

for _, row in top3_days.iterrows():

    # 날짜를 사람이 읽기 좋은 형태로 만듭니다.
    date_text = row["날짜"].strftime("%m/%d")

    fig3.add_annotation(
        x=row["날짜"],
        y=row["일관객"],
        text=(
            f"{date_text}<br>"
            f"{row['일관객']:,}명"
        ),
        showarrow=True,
        arrowhead=2,
        yshift=10
    )


fig3.update_layout(
    hovermode="x",
    height=600
)


# 그래프 출력
st.plotly_chart(
    fig3,
    use_container_width=True
)


# --------------------------------------------------
# 세 번째 그래프 해석 공간
# --------------------------------------------------

st.markdown("**이 그래프로 알 수 있는 것**")

st.text_area(
    "세 번째 그래프에서 발견한 점을 적어 보세요.",
    placeholder=(
        "예: 특정 날짜에 10위권 영화의 관객수가 "
        "전체적으로 크게 증가한 것을 확인할 수 있다."
    ),
    height=100,
    key="graph3_note"
)


# ==================================================
# 앞으로 그래프를 추가할 공간
# ==================================================

st.divider()

st.header("4. 다음 그래프")

st.info(
    "새로운 데이터 분석 그래프를 추가할 공간입니다."
)

st.markdown("**이 그래프로 알 수 있는 것**")

st.text_area(
    "네 번째 그래프에서 발견한 점을 적어 보세요.",
    placeholder="새로운 그래프를 추가한 뒤 내용을 적어 보세요.",
    height=100,
    key="graph4_note"
)


# ==================================================
# 데이터 출처
# ==================================================

st.divider()

st.caption(
    "데이터 출처: 영화관입장권통합전산망(KOBIS) "
    "일일 박스오피스 데이터"
)
